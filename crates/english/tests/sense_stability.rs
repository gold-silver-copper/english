//! Golden regression tests pinning the meaning of published, sense-numbered keys.
//!
//! These lock in the public contract that the assignment lockfiles exist to
//! protect: a key like `lie_2` or `die_2` must keep producing the same inflection
//! across releases. If a data refresh ever renumbers a homograph, one of these
//! fails loudly instead of silently shipping a swapped meaning.

use english::{Degree, English, Form, Number, Person, Tense, count};

fn past_finite(word: &str) -> String {
    English::verb(
        word,
        &Person::Third,
        &Number::Singular,
        &Tense::Past,
        &Form::Finite,
    )
}

#[test]
fn verb_lie_homographs_are_pinned() {
    // Both homograph senses stay distinct and pinned. The bare-vs-`2` assignment is
    // driven by the (stable) senseid ordering: "lie" (tell an untruth) -> lied ;
    // "lie_2" (recline) -> lay.
    assert_eq!(past_finite("lie"), "lied");
    assert_eq!(past_finite("lie_2"), "lay");
}

#[test]
fn noun_die_homograph_is_pinned() {
    assert_eq!(English::noun("die_2", &Number::Plural), "dice");
}

#[test]
fn adjective_bad_is_pinned_to_the_standard_suppletive() {
    // The standard sense holds the bare key with the suppletive forms (standard
    // sorts before soft at cold start). The slang sense's badder/baddest equal
    // the CVC rule prediction, but since `worse` occupies the bare key the rule
    // can never serve them — so they are published at the next numbered key,
    // with the slang periphrastic variant after that.
    assert_eq!(English::adj("bad", &Degree::Comparative), "worse");
    assert_eq!(English::adj("bad", &Degree::Superlative), "worst");
    assert_eq!(English::adj("bad_2", &Degree::Comparative), "badder");
    assert_eq!(English::adj("bad_2", &Degree::Superlative), "baddest");
}

#[test]
fn bare_keys_serve_the_canonical_irregular() {
    // The words that motivated the plain-only reservation policy: a soft-tagged
    // regular ("sheeps") or a formless uncomparable sense must not demote the
    // canonical irregular off the bare key.
    assert_eq!(English::noun("sheep", &Number::Plural), "sheep");
    assert_eq!(English::adj("fast", &Degree::Comparative), "faster");
    assert_eq!(English::adj("fast", &Degree::Superlative), "fastest");
    assert_eq!(English::adj("hot", &Degree::Comparative), "hotter");
    assert_eq!(English::adj("good", &Degree::Superlative), "best");
    // ...while a plainly-attested regular still reserves the bare key: the bare
    // "die" stays regular ("dies") and the irregular sense lives at die_2.
    assert_eq!(English::noun("die", &Number::Plural), "dies");
    assert_eq!(English::noun("die_2", &Number::Plural), "dice");
    // A genuinely periphrastic adjective keeps rule output on the bare key.
    assert_eq!(English::adj("fun", &Degree::Comparative), "more fun");
}

#[test]
fn trailing_digits_strip_only_for_real_table_keys() {
    // A trailing-digit run is a sense suffix ONLY when it resolves to a table key.
    // Known suffixed keys strip and resolve; their bare form is the stripped lemma.
    assert_eq!(English::noun("die_2", &Number::Plural), "dice");
    assert_eq!(English::noun("die_2", &Number::Singular), "die");
    // "good_2" is no longer a published key (good holds the bare key), but as a
    // suffixed alias of a bare irregular key it resolves through the base lemma.
    assert_eq!(English::adj("good_2", &Degree::Superlative), "best");

    // Digit-bearing words that are NOT table keys are opaque — never corrupted into
    // a digit-stripped stem (this is the strip_trailing_number bug fix).
    assert_eq!(English::noun("mp3", &Number::Plural), "mp3s");
    assert_eq!(English::noun("F16", &Number::Plural), "F16s");
    assert_eq!(English::noun("co2", &Number::Plural), "co2s");
    assert_eq!(English::noun("i7", &Number::Singular), "i7");
    assert_eq!(past_finite("mp3"), "mp3ed");

    // count() ergonomic helper must not mangle a digit-bearing noun.
    assert_eq!(count("F16", 3), "F16s");

    // A numbered key for a REGULAR lemma is never generated by the library, so it is
    // treated opaquely rather than stripped to the bare lemma.
    assert_eq!(English::noun("cat_2", &Number::Plural), "cat_2s");
    // The old failure mode is structurally impossible now: "F2" has no underscore,
    // so it can never collide with a sense suffix even though "f" is a table key.
    assert_eq!(English::noun("F2", &Number::Plural), "F2s");
}

#[test]
fn attested_variants_are_numbered_keys_in_listing_order() {
    // Every plain attested variant is its own numbered key. abide attests the
    // regular conjugation too, so the bare key serves the rule (abided) — like
    // die/die_2 — while the first-LISTED irregular (abode, the canonical form,
    // not the lexicographic accident "abid") takes the lowest numbered key and
    // the archaic variant the next one.
    assert_eq!(past_finite("abide"), "abided");
    assert_eq!(past_finite("abide_2"), "abode");
    assert_eq!(past_finite("abide_3"), "abid");
    // crow: bare serves the regular "crowed"; the British variant is crow_2.
    assert_eq!(past_finite("crow"), "crowed");
    assert_eq!(past_finite("crow_2"), "crew");
    // dive: bare regular "dived"; the North American irregular is dive_2.
    assert_eq!(past_finite("dive"), "dived");
    assert_eq!(past_finite("dive_2"), "dove");
}

#[test]
fn table_column_order_is_pinned() {
    // Canary for the lock -> table emitter. check-registry's sync gate
    // regenerates tables with the SAME in-tree emitter it verifies, so an
    // emitter bug that permutes columns (past <-> past participle, comparative
    // <-> superlative) would pass it by construction. These keys have pairwise
    // DISTINCT column values, so any permutation fails here instead: regular
    // pairs like lied/lied can't detect a swap, went/gone/going/goes can.
    assert_eq!(
        English::verb(
            "go",
            &Person::Third,
            &Number::Singular,
            &Tense::Present,
            &Form::Finite
        ),
        "goes"
    );
    assert_eq!(past_finite("go"), "went");
    assert_eq!(
        English::verb(
            "go",
            &Person::Third,
            &Number::Singular,
            &Tense::Present,
            &Form::Participle
        ),
        "going"
    );
    assert_eq!(
        English::verb(
            "go",
            &Person::Third,
            &Number::Singular,
            &Tense::Past,
            &Form::Participle
        ),
        "gone"
    );
    assert_eq!(English::adj("good", &Degree::Comparative), "better");
    assert_eq!(English::adj("good", &Degree::Superlative), "best");
    assert_eq!(English::noun("child", &Number::Plural), "children");
}

#[test]
fn acronym_homographs_never_hit_shadowing_table_rows() {
    // "US" (the acronym) lowercases to the attested irregular row "us" => "uss";
    // the case-folded fallback must skip such shadowed rows and inflect by rule
    // instead of publishing "USS". Lowercase "us" itself still hits the table.
    assert_eq!(English::noun("US", &Number::Plural), "USES");
    assert_eq!(English::noun("Us", &Number::Plural), "Uses");
    assert_eq!(English::noun("us", &Number::Plural), "uss");
}

#[test]
fn capitalized_input_preserves_its_casing() {
    // Tables are all-lowercase; Title-case and ALL-CAPS input must still hit them,
    // with the casing restored on the value. Regular-rule fallbacks always
    // preserved casing naturally (they build on the input string).
    assert_eq!(English::noun("Child", &Number::Plural), "Children");
    assert_eq!(English::noun("CHILD", &Number::Plural), "CHILDREN");
    assert_eq!(English::noun("Cat", &Number::Plural), "Cats"); // rule path
    assert_eq!(past_finite("Go"), "Went");
    assert_eq!(English::adj("Good", &Degree::Superlative), "Best");
    // A numbered key still resolves case-insensitively.
    assert_eq!(English::noun("Die_2", &Number::Plural), "Dice");
    // Regular-rule fallbacks get the SAME casing treatment as table hits: HOT
    // must give HOTTER exactly as GOOD gives BEST — never mixed-case "HOTter".
    assert_eq!(English::adj("HOT", &Degree::Comparative), "HOTTER");
    assert_eq!(English::adj("HAPPY", &Degree::Superlative), "HAPPIEST");
    assert_eq!(English::noun("CAT", &Number::Plural), "CATS");
    assert_eq!(English::adj("Happy", &Degree::Comparative), "Happier");
    // Mixed case is not guessed at: table lookups miss and the rule applies.
    assert_eq!(English::noun("McDonald", &Number::Plural), "McDonalds");
}

#[test]
fn suffixed_alias_of_bare_irregular_key_inflects_as_the_base_lemma() {
    // When stripping applies because the STRIPPED form is a table key (the word
    // itself is not), every inflection must agree that the input denotes that base
    // lemma. Regression: the singular/infinitive used to strip while the
    // plural/past fell through to the regular rule ("childs", "goed").
    assert_eq!(English::noun("child_2", &Number::Singular), "child");
    assert_eq!(English::noun("child_2", &Number::Plural), "children");
    assert_eq!(past_finite("go_7"), "went");
    assert_eq!(
        English::verb(
            "go_7",
            &Person::Third,
            &Number::Singular,
            &Tense::Present,
            &Form::Infinitive
        ),
        "go"
    );
}
